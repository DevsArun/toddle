_COUNT_COLOURS = [RED, ORANGE, YELLOW, GREEN, TEAL, BLUE, INDIGO, PURPLE,
                  PINK, BROWN]


def _counting_page(n):
    """Build a counting page: a card plus n coloured dots in a tidy grid."""
    parts = [
        rr(0, 0, 1000, 1000, 0, SKY),
        rr(80, 120, 920, 880, 40, CREAM),
        rr(140, 180, 860, 820, 30, WHITE),
    ]
    cols = 5
    rows = (n + cols - 1) // cols
    cell = 130
    radius = 46
    grid_h = rows * cell
    top = 500 - grid_h // 2
    for i in range(n):
        row = i // cols
        col = i % cols
        in_row = min(cols, n - row * cols)
        row_w = in_row * cell
        left = 500 - row_w // 2
        cx = left + col * cell + cell // 2
        cy = top + row * cell + cell // 2
        parts.append(ci(cx, cy, radius, _COUNT_COLOURS[i % len(_COUNT_COLOURS)]))
    return ("%s (%d)" % (_NUMBER_WORDS[n], n), parts)


